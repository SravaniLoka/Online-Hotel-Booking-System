    @Override
    public boolean delete(long bookingId) {

        String sql = "DELETE FROM booking WHERE booking_id = ?";

        try (Connection connection = DBConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {

            statement.setLong(1, bookingId);

            return statement.executeUpdate() > 0;

        } catch (SQLException e) {
            e.printStackTrace();
        }

        return false;
    }

    private Booking mapResultSetToBooking(ResultSet resultSet)
            throws SQLException {

        User user = new User();
        user.setUserId(resultSet.getLong("user_id"));

        Hotel hotel = new Hotel();
        hotel.setHotelId(resultSet.getLong("hotel_id"));

        Room room = new Room();
        room.setRoomId(resultSet.getLong("room_id"));

        return new Booking(
                resultSet.getLong("booking_id"),
                user,
                hotel,
                room,
                resultSet.getDate("check_in_date"),
                resultSet.getDate("check_out_date"),
                resultSet.getInt("guests"),
                resultSet.getBigDecimal("total_amount"),
                resultSet.getString("booking_status")
        );
    }
